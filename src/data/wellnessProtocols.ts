export function findWellnessProtocol(id: string): WellnessProtocol | undefined {
  return wellnessProtocols.find((item) => item.id === id)
}

export function formatWellnessProtocol(protocol: WellnessProtocol, companyName?: string | null): string {
  const brand = companyName?.trim() || 'tu empresa'
  const lines = [
    `🌟 ${protocol.label} 🌟`,
    '',
    protocol.focus,
    '',
    `🌿 Recomendaciones ${brand}:`,
    '',
    ...protocol.products.flatMap((product) => [`💊 ${product.name}`, product.usage, '']),
  ]

  if (protocol.extra) {
    lines.push(protocol.extra, '')
  }

  lines.push(
    `Esta información es orientativa según el catálogo de ${brand}. No sustituye el consejo médico profesional. Consulte siempre a su médico antes de iniciar cualquier suplemento.`,
  )

  return lines.join('\n')
}
